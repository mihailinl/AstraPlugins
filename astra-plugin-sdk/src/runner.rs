//! Plugin runner — CLI args, gRPC server, registration, lifecycle, shutdown.
//!
//! # Startup order
//!
//! ```text
//! bind  →  register  →  build ctx  →  on_config  →  on_language_changed
//!       →  on_start  →  serve
//! ```
//!
//! Each step depends on the one before it and on nothing after it, which is the
//! only reason the order is fixed. `bind` comes before `register` because the
//! daemon is told the port during `Register` and may call back immediately —
//! the listener is up, so those calls queue in the accept backlog instead of
//! being refused. `on_config` and `on_language_changed` come before `on_start`
//! because a plugin that starts a background loop needs its settings first;
//! before 0.6 they ran in the other order and every example worked around it.
//! `on_start` comes before `serve` because an `Err` there **aborts startup**:
//! a plugin that cannot do its job must not be a plugin the daemon believes is
//! healthy.

