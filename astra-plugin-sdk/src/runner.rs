    type SttProcessStream = std::pin::Pin<
        Box<dyn tokio_stream::Stream<Item = Result<proto::PluginSttEvent, tonic::Status>> + Send>,
    >;

    async fn stt_process(
        &self,
        request: tonic::Request<tonic::Streaming<proto::PluginAudioChunk>>,
    ) -> Result<tonic::Response<Self::SttProcessStream>, tonic::Status> {
        let mut inbound = request.into_inner();

        // Set up the streaming bridge: a channel of `Vec<u8>` chunks
        // (f32 LE PCM, no sample-rate boundaries) flows from the inbound
        // gRPC stream into the plugin, and `SttEvent`s flow back out into
        // the outbound stream.
        //
        // Capacity comes from `spec/limits.yaml`, which the daemon's end of
        // this bridge asserts against at compile time — the two channels are in
        // series, so the smaller one is the real capacity. The old hardcoded 32
        // was that silent bottleneck: the worst-case wake-seed dump (~8 s of
        // 16 kHz audio in 1600-sample batches ≈ 80) plus live audio piling up
        // overflowed it, so STT only ever saw the first fraction of an
        // utterance — while both files carried a comment promising lockstep.
        let (audio_tx, audio_rx) = tokio::sync::mpsc::channel::<Vec<u8>>(
            crate::limits::STT_AUDIO_CHANNEL_CAPACITY as usize,
        );
        let (events_tx, events_rx) = tokio::sync::mpsc::channel::<SttEvent>(8);

        // Peek the first chunk to learn the sample rate and the per-utterance
        // decoding options before spawning the plugin task — both are on the
        // first chunk only, and `stt_transcribe_stream` needs them up front.
        let first = match inbound.message().await? {
            Some(c) => c,
            None => {
                // Empty stream — nothing to transcribe.
                let empty: Self::SttProcessStream = Box::pin(tokio_stream::empty());
                return Ok(tonic::Response::new(empty));
            }
        };
        let sample_rate = first.sample_rate;
        let options = first.options.unwrap_or_default();
        let first_is_last = first.is_last;
        if !first.data.is_empty() {
            let _ = audio_tx.send(first.data).await;
        }

        // Inbound forwarder: pump every subsequent `PluginAudioChunk`'s
        // `data` into the audio channel until `is_last` or end-of-stream,
        // then drop the sender to signal end-of-utterance.
        if !first_is_last {
            let inbound_tx = audio_tx.clone();
            tokio::spawn(async move {
                while let Ok(Some(chunk)) = inbound.message().await {
                    if !chunk.data.is_empty() && inbound_tx.send(chunk.data).await.is_err() {
                        break;
                    }
                    if chunk.is_last {
                        break;
                    }
                }
                drop(inbound_tx);
            });
        }
        drop(audio_tx);

        // Plugin task: run `stt_transcribe_stream`. Default impl buffers
        // and forwards to `stt_transcribe` — so a non-streaming plugin
        // works without changes. A streaming-capable plugin (echo-stt,
        // a future Vosk wrapper) overrides the hook and consumes chunks
        // live.
        let plugin = self.plugin.clone();
        let ctx = self.ctx.clone();
        let task = tokio::spawn(async move {
            plugin
                .stt_transcribe_stream(&ctx, audio_rx, events_tx, sample_rate, options)
                .await
        });

        // Outbound forwarder: map every `SttEvent` to a proto event on
        // the response stream. Closes when `events_tx` is dropped by the
        // plugin task — and then reports how that task ended.
        //
        // The hook's `Err` is part of the answer, not a log line. It used to be
        // `warn!`ed and dropped, which made a plugin that declares `stt` and
        // does not implement `stt_transcribe` answer `SttProcess` with OK and
        // zero events — while Python and TypeScript both answered
        // UNIMPLEMENTED. That broke the protocol's own forward-compat contract
        // ("Unimplemented means the hook is absent") in the language most
        // plugins are written in, and it swallowed genuine mid-utterance
        // recognizer failures with it: the user saw a moving waveform, no text,
        // and nothing in the daemon log.
        //
        // Yielded *after* the events rather than awaited before them, unlike
        // `TtsSynthesizeStream`: a non-streaming STT plugin emits nothing until
        // the utterance ends, so waiting for a first event before answering
        // would hold the response headers for the whole utterance. Zero events
        // followed by an `Err` reaches the client as the status anyway, because
        // no message has been sent yet.
        let out = async_stream::stream! {
            let mut events_rx = events_rx;
            while let Some(ev) = events_rx.recv().await {
                let proto_ev: proto::PluginSttEvent = ev.into();
                yield Ok::<proto::PluginSttEvent, tonic::Status>(proto_ev);
            }
            match task.await {
                Ok(Ok(())) => {}
                Ok(Err(e)) => yield Err(hook_status(e)),
                Err(e) => yield Err(tonic::Status::internal(format!(
                    "stt_transcribe_stream panicked: {e}"
                ))),
            }
        };
        Ok(tonic::Response::new(Box::pin(out)))
    }

