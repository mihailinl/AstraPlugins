/// Dispatch a daemon event to the appropriate typed handler on the plugin.
/// Also always calls `on_event()` for the raw payload.
///
/// `pub(crate)` so the level-1 test harness delivers events through the same
/// code the runner does — a harness with its own dispatch would be testing
/// itself.
pub(crate) async fn dispatch_event<P: PluginCapability>(
    plugin: &P,
    ctx: &PluginContext,
    event: &proto::PluginEventMsg,
) {
    match event.event_type.as_str() {
        "state_changed" => {
            if let Ok(parsed) = serde_json::from_str::<events::StateChangedEvent>(&event.payload_json) {
                plugin.on_state_changed(ctx, parsed).await;
            }
        }
        "command_triggered" => {
            if let Ok(parsed) = serde_json::from_str::<events::CommandTriggeredEvent>(&event.payload_json) {
                plugin.on_command_triggered(ctx, parsed).await;
            }
        }
        "command_completed" => {
            if let Ok(parsed) = serde_json::from_str::<events::CommandCompletedEvent>(&event.payload_json) {
                plugin.on_command_completed(ctx, parsed).await;
            }
        }
        _ => {}
    }
    plugin.on_event(ctx, &event.event_type, &event.payload_json).await;
}

/// CLI arguments passed by the Astra daemon when spawning a plugin.
#[derive(Parser, Debug)]
#[command(name = "astra-plugin")]
struct Args {
    /// Daemon gRPC address (host:port).
    #[arg(long)]
    daemon_addr: String,

    /// Plugin ID (from manifest).
    #[arg(long)]
    plugin_id: String,

    /// Auth token for registration verification (generated by daemon).
    #[arg(long, default_value = "")]
    auth_token: String,

    /// The `[capabilities]` this plugin's manifest declares, comma-separated.
    ///
    /// The daemon reads `plugin.toml` — which it, not the plugin, can locate —
    /// and passes the result here.
    #[arg(long, value_delimiter = ',')]
    capabilities: Vec<String>,
}

/// The flags the daemon spawns a plugin with. Everything else on the command
/// line belongs to the plugin.
const DAEMON_FLAGS: &[&str] = &[
    "--daemon-addr",
    "--plugin-id",
    "--auth-token",
    "--capabilities",
];

/// Ask a plugin binary what capabilities it was built with, one per line, and
/// exit 0. Used by `astra-plugin check` to cross-check the manifest against the
/// binary without a daemon; emitted by `#[astra::plugin]`, which knows the
/// answer at compile time.
const PRINT_CAPABILITIES_FLAG: &str = "--print-capabilities";

/// Keep only the daemon's own flags out of `argv`.
///
/// A plugin is a normal binary and may define its own CLI (`--verbose`, a
/// subcommand, …). `Args::parse()` would abort the whole process on the first
/// argument it does not know, so the SDK filters argv down to what it owns and
/// silently leaves the rest to the plugin.
fn daemon_args(argv: impl IntoIterator<Item = String>) -> Vec<String> {
    let mut argv = argv.into_iter();
    let mut out = vec![argv.next().unwrap_or_else(|| "astra-plugin".to_string())];

    while let Some(arg) = argv.next() {
        if let Some((flag, _)) = arg.split_once('=')
            && DAEMON_FLAGS.contains(&flag)
        {
            out.push(arg);
        } else if DAEMON_FLAGS.contains(&arg.as_str()) {
            // `--flag value` — take the value with it, or the flag alone if the
            // caller truncated it (clap reports the missing value).
            out.push(arg);
            if let Some(value) = argv.next() {
                out.push(value);
            }
        }
    }

    out
}

/// The environment variable the daemon states `[capabilities]` in.
///
/// **The daemon uses the environment and not argv, and the reason is a
/// compatibility bug that would have been ours.** The list was briefly appended
/// as `--capabilities=<list>`, on the reasoning that a plugin binary already in
/// the field scans argv for the prefixes it knows and ignores the rest. True of
/// this SDK ([`daemon_args`] filters argv down to the flags it owns) and of the
/// TypeScript one — and false of the published Python SDK 0.4.0, which parses
/// argv with `argparse.parse_args()` and exits 2 on an unrecognised argument
/// before it ever binds its port. A variable a process does not read cannot
/// break it, so that is the channel.
///
/// Present-but-empty means "this manifest declares none". *Absent* means the
/// daemon predates §5.4 — see [`resolve_capabilities`].
const CAPABILITIES_ENV: &str = "ASTRA_PLUGIN_CAPABILITIES";

/// What the daemon stated in the environment, or `None` if it stated nothing.
///
/// `Some(vec![])` and `None` are different answers and the difference matters:
/// the first is "you were granted nothing", the second is "nobody told me".
fn capabilities_from_env() -> Option<Vec<String>> {
    std::env::var(CAPABILITIES_ENV)
        .ok()
        .map(|v| v.split(',').map(|s| s.trim().to_string()).collect())
}

/// Decide what capability list to send at registration.
///
/// **The manifest is the source of truth, and the plugin cannot read it.** In a
/// packaged bundle `plugin.toml` sits at the install root while the executable
/// is under `bin/`, so `std::env::current_exe().parent().join("plugin.toml")` —
/// what every "just read the manifest" design ends up as — finds nothing. The
/// daemon has already parsed the manifest to decide whether to spawn this
/// process at all, so it passes the answer down.
///
/// The order is: an explicit `--capabilities` on argv (no daemon sends one
/// today, but a harness or a `dev` sideload may), else
/// [`CAPABILITIES_ENV`], else what the binary was built to declare
/// ([`RunConfig::capabilities`], which `#[astra::plugin]` fills in), else
/// nothing plus a warning. It is never *inferred* from which trait methods
/// return non-empty vectors — that was 0.5's `discover_capabilities`, and it
/// made a plugin's capability set depend on whether a list happened to be empty
/// at startup, silently disagreeing with the manifest the user consented to.
fn resolve_capabilities(
    from_argv: Vec<String>,
    from_env: Option<Vec<String>>,
    declared: &[String],
) -> Vec<String> {
    let clean = |v: Vec<String>| -> Vec<String> {
        v.into_iter()
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect()
    };

    let from_argv = clean(from_argv);
    if !from_argv.is_empty() {
        return from_argv;
    }
    // `Some` is the daemon speaking, even when the list is empty: this manifest
    // declares nothing, and falling back to what the binary was built with would
    // override the file the user actually consented to.
    if let Some(stated) = from_env {
        let stated = clean(stated);
        if stated.is_empty() {
            warn!(
                "The daemon says this plugin's manifest declares no capabilities. \
                 No hook will be called. Add a `[capabilities]` section to \
                 plugin.toml."
            );
        }
        return stated;
    }
    let declared = clean(declared.to_vec());
    if !declared.is_empty() {
        warn!(
            "The daemon stated no capabilities ({CAPABILITIES_ENV} is unset); \
             falling back to the {} this binary declares. An Astra older than \
             the one this SDK targets does not state them.",
            declared.len()
        );
        return declared;
    }
    warn!(
        "Registering with NO capabilities: the daemon stated none and this \
         binary declares none. The daemon will not call any hook. Pass \
         RunConfig::capabilities, or use #[astra::plugin], which fills it in."
    );
    Vec::new()
}

/// Optional knobs for [`run_with`].
///
/// Constructed with `RunConfig::default()` and adjusted field by field; it is
/// `#[non_exhaustive]` so new knobs are not breaking changes.
#[derive(Debug, Clone)]
#[non_exhaustive]
pub struct RunConfig {
    /// Install the SDK's `tracing_subscriber`. Leave `true` unless the plugin
    /// installs its own — the SDK uses `try_init`, so a subscriber the plugin
    /// set up first simply wins and this is a no-op.
    pub init_tracing: bool,

    /// Argv to parse instead of `std::env::args()`.
    pub argv: Option<Vec<String>>,

    /// Address the plugin's gRPC server binds. Port 0 means OS-assigned; the
    /// bound port is what gets reported to the daemon at registration.
    ///
    /// SECURITY: loopback only. Loopback is not a boundary between processes of
    /// the same user, so it is `capability_auth` — not this address — that keeps
    /// another local process out of the plugin's tools.
    pub bind_addr: SocketAddr,

    /// How strictly the plugin's capability server checks that an inbound call
    /// really came from the daemon that spawned it.
    ///
    /// See [`CapabilityAuth`]. The `ASTRA_PLUGIN_CAPABILITY_AUTH` environment
    /// variable overrides whatever is set here, so an operator can enforce (or
    /// disable) the check without rebuilding the plugin.
    pub capability_auth: CapabilityAuth,

    /// The capabilities this binary was built to serve — the fallback when the
    /// daemon passes no `--capabilities`, and the answer to
    /// `--print-capabilities`.
    ///
    /// The daemon's list always wins: it read the manifest, which is the thing
    /// the user consented to. This is what an Astra too old to send the flag
    /// falls back to.
    pub capabilities: Vec<String>,
}

impl Default for RunConfig {
    fn default() -> Self {
        Self {
            init_tracing: true,
            argv: None,
            bind_addr: SocketAddr::from(([127, 0, 0, 1], 0)),
            capability_auth: CapabilityAuth::default(),
            capabilities: Vec::new(),
        }
    }
}

/// Run a plugin. Call this from your `main()`.
///
/// Returns `Err` if binding, registration, `on_start` or serving fails —
/// propagate it out of `main` so the exit code is non-zero and the daemon sees
/// the failure.
pub async fn run<P: PluginCapability>(plugin: P) -> Result<()> {
    run_with(plugin, RunConfig::default()).await
}

/// [`run`] with explicit configuration.
pub async fn run_with<P: PluginCapability>(plugin: P, config: RunConfig) -> Result<()> {
    // Before anything that can panic — including the argument parse. A panic
    // the hook was not installed for is one nobody can read afterwards.
    crate::panics::install_hook();

    if config.init_tracing {
        use tracing_subscriber::layer::SubscriberExt;
        use tracing_subscriber::util::SubscriberInitExt;
        // `try_init`, not `init`: a plugin that installed its own subscriber (or
        // a second `run_with` in one process, as in tests) must not panic here.
        //
        // Two layers: stderr, which the daemon captures, and the host layer,
        // which turns the author's own `tracing::info!` into a `PluginLog` the
        // *user* can read in the plugin's log pane. It is inert until
        // `logging::attach` hands it a host client, below.
        let _ = tracing_subscriber::registry()
            .with(
                tracing_subscriber::EnvFilter::try_from_default_env()
                    .unwrap_or_else(|_| "info".into()),
            )
            .with(tracing_subscriber::fmt::layer())
            .with(crate::logging::layer())
            .try_init();
    }

    let argv = config
        .argv
        .clone()
        .unwrap_or_else(|| std::env::args().collect::<Vec<_>>());

    // Answered before anything else: `--print-capabilities` is a question about
    // the binary, not a request to run it, and it must work with no daemon,
    // no --plugin-id and no network.
    if argv.iter().any(|a| a == PRINT_CAPABILITIES_FLAG) {
        for cap in &config.capabilities {
            println!("{cap}");
        }
        return Ok(());
    }

    let args = Args::parse_from(daemon_args(argv));
    info!(
        "Starting plugin '{}', connecting to daemon at {}",
        args.plugin_id, args.daemon_addr
    );

    let plugin = Arc::new(plugin);

    // ── bind ──
    // Before registering: the daemon is told the port during Register and may
    // call back immediately.
    let listener = TcpListener::bind(config.bind_addr)
        .await
        .with_context(|| format!("Failed to bind {}", config.bind_addr))?;
    let local_addr: SocketAddr = listener.local_addr()?;
    let port = local_addr.port();
    info!("Plugin gRPC server listening on port {}", port);

    // ── register ──
    // `connect_bootstrap` can only Register; `register` consumes it and returns
    // the client that carries the session token.
    let bootstrap = HostClient::connect_bootstrap(&args.daemon_addr, args.plugin_id.clone()).await?;

    let capabilities = resolve_capabilities(
        args.capabilities,
        capabilities_from_env(),
        &config.capabilities,
    );
    info!("Registering with capabilities: {:?}", capabilities);
    let is_client_plugin =
        plugin.is_client() || capabilities.iter().any(|c| c == "client");

    let (host, reg_response) = match bootstrap
        .register(port, capabilities, args.auth_token.clone())
        .await
    {
        Ok(pair) => pair,
        Err(e) => {
            // A protocol mismatch is not a fault to retry, log a backtrace for,
            // or bury in a `Result` the caller turns into "plugin exited 1". It
            // is one fact with one fix. Say it on stderr — where the daemon
            // captures plugin output and the user reads it in the plugin's log
            // pane — and leave with EX_CONFIG.
            if let Some(mismatch) = e.downcast_ref::<crate::protocol::ProtocolMismatch>() {
                eprintln!("{mismatch}");
                std::process::exit(crate::protocol::EXIT_PROTOCOL_INCOMPATIBLE);
            }
            return Err(e);
        }
    };
    info!(
        "Registered successfully. Daemon version: {}, protocol: {} (accepts {}+)",
        reg_response.daemon_version, reg_response.protocol_version, reg_response.min_supported_protocol
    );

    // ── build ctx ──
    let host = Arc::new(host);

    // From here on, `tracing::warn!("…")` in the plugin's own code reaches the
    // user's log pane and not just stderr. Registration is the earliest this
    // can happen: before it there is no authenticated client to send on.
    crate::logging::attach(host.clone() as Arc<dyn Host>);

    let mut ctx = PluginContext::new(args.plugin_id.clone(), host.clone() as Arc<dyn Host>);

    // Background loops (chat firehose, event subscription). Kept so shutdown
    // stops them instead of leaving them running against a dead host client.
    let mut background: Vec<JoinHandle<()>> = Vec::new();

    // A client-capable plugin gets the full daemon API. Gated on the capability,
    // not on the token being non-empty: the daemon issues a session token to
    // EVERY plugin (host_service.rs, SECURITY(B1)) because every host RPC needs
    // one, so an empty-token test says nothing about capability.
    if is_client_plugin && !reg_response.client_session_token.is_empty() {
        let daemon_client = crate::DaemonClient::connect(
            &args.daemon_addr,
            reg_response.client_session_token.clone(),
        )
        .await?;
        ctx = ctx.with_daemon(Arc::new(daemon_client));
        info!("DaemonClient connected (plugin has client capability)");
    }

    if !reg_response.language.is_empty() {
        ctx.set_language(reg_response.language.clone());
    }

    // Published for background tasks that cannot be handed a parameter — see
    // `crate::ctx()`. Handlers are given `&PluginContext` and should use that.
    install_context(ctx.clone());

    // ── on_config ──
    // Before on_start, so a plugin that starts a background loop has its
    // settings. `on_config_changed` defaults to parse-then-delegate.
    if !reg_response.config_json.is_empty() {
        plugin.on_config_changed(&ctx, &reg_response.config_json).await;
    }

    // ── on_language_changed ──
    if !reg_response.language.is_empty() {
        plugin.on_language_changed(&ctx, &reg_response.language).await;
    }

    // ── on_start ──
    // An Err here aborts startup. The plugin never serves and the process exits
    // non-zero, which is what the daemon needs to see.
    // A panic here is still an aborted startup — but it arrives as one
    // sentence naming `on_start` and the line, rather than as an unwind out of
    // `main` that the daemon reads as "exited 101".
    match crate::panics::catch("on_start", plugin.on_start(&ctx)).await {
        Ok(res) => res.context("Plugin on_start failed; aborting startup")?,
        Err(panicked) => {
            return Err(anyhow::anyhow!("{panicked}")
                .context("Plugin on_start panicked; aborting startup"));
        }
    }

    // Firehose loop: on_conversation_event for every chat event. Fetch the
    // conversation list first and subscribe with cursor=0 for each so plugins
    // receive the full event history on startup in addition to live events.
    if let Some(daemon) = ctx.daemon().cloned() {
        let plugin_for_chat = plugin.clone();
        let ctx_for_chat = ctx.clone();
        background.push(tokio::spawn(async move {
            loop {
                let cursors: std::collections::HashMap<String, u64> =
                    match daemon.list_conversations().await {
                        Ok(resp) => resp
                            .conversations
                            .iter()
                            .map(|c| (c.id.clone(), 0u64))
                            .collect(),
                        Err(e) => {
                            tracing::warn!("list_conversations failed: {e}");
                            std::collections::HashMap::new()
                        }
                    };
                match daemon.subscribe_chat_events(cursors).await {
                    Ok(mut stream) => {
                        info!("Chat firehose active");
                        use tokio_stream::StreamExt;
                        while let Some(msg) = stream.next().await {
                            match msg {
                                Ok(fe) => {
                                    if let Some(event) = fe.event {
                                        plugin_for_chat
                                            .on_conversation_event(
                                                &ctx_for_chat,
                                                &fe.conversation_id,
                                                &event,
                                            )
                                            .await;
                                    }
                                }
                                Err(e) => {
                                    tracing::warn!("Chat firehose error: {e}, will reconnect");
                                    break;
                                }
                            }
                        }
                        info!("Chat firehose stream ended, reconnecting...");
                    }
                    Err(e) => {
                        tracing::warn!("Chat firehose subscribe failed: {e}, retrying...");
                    }
                }
                tokio::time::sleep(std::time::Duration::from_secs(2)).await;
            }
        }));
    }

    // Start daemon-event subscription if the plugin wants host-level events.
    // Chat events are NOT here — they come via the firehose above.
    let event_types = plugin.subscribed_events();
    if !event_types.is_empty() {
        info!("Subscribing to daemon events: {:?}", event_types);
        let plugin_for_events = plugin.clone();
        let ctx_for_events = ctx.clone();
        let host_for_events = host.clone();
        background.push(tokio::spawn(async move {
            loop {
                match host_for_events
                    .subscribe_events(event_types.clone(), String::new())
                    .await
                {
                    Ok(mut stream) => {
                        info!("Event subscription active");
                        use tokio_stream::StreamExt;
                        while let Some(msg) = stream.next().await {
                            match msg {
                                Ok(event) => {
                                    dispatch_event(&*plugin_for_events, &ctx_for_events, &event)
                                        .await;
                                }
                                Err(e) => {
                                    tracing::warn!("Event stream error: {e}, will reconnect");
                                    break;
                                }
                            }
                        }
                        info!("Event subscription stream ended, reconnecting...");
                    }
                    Err(e) => {
                        tracing::warn!("Event subscription failed: {e}, retrying...");
                    }
                }
                tokio::time::sleep(std::time::Duration::from_secs(2)).await;
            }
        }));
    }

    // ── serve ──
    // The oneshot below is the single shutdown path: signals and the daemon's
    // `Shutdown` RPC both fire it, tonic then stops accepting and drains
    // in-flight requests (so `Shutdown` gets its reply), and `on_shutdown()`
    // runs exactly once after the server is down.
    let (shutdown_tx, shutdown_rx) = oneshot::channel::<()>();
    let shutdown = ShutdownTrigger::new(shutdown_tx);
    let svc = CapabilityServiceImpl {
        plugin: plugin.clone(),
        ctx: ctx.clone(),
        shutdown: shutdown.clone(),
    };

    // SECURITY: the capability server is the daemon's way into this plugin's
    // tools, config and shutdown, and loopback separates it from nothing — any
    // process of the same user can dial the port. The guard demands the daemon
    // hand back the spawn-time `--auth-token`, which only it and this process
    // know. Staged: see `CapabilityAuth`.
    let guard = CapabilityInterceptor::new(&args.auth_token, config.capability_auth.resolved());
    if !guard.is_active() {
        warn!(
            "Capability server is unauthenticated — any local process can call this plugin. \
             (No --auth-token was passed, or the check is switched off.)"
        );
    }
    let server = Server::builder()
        .add_service(PluginCapabilityServiceServer::with_interceptor(svc, guard))
        .serve_with_incoming_shutdown(
            tokio_stream::wrappers::TcpListenerStream::new(listener),
            async move {
                // A dropped sender (no trigger ever fired) also means "stop".
                let _ = shutdown_rx.await;
            },
        );

    let mut server_handle = tokio::spawn(server);

    // Serve until the server finishes on its own (daemon `Shutdown`, or an
    // error) or the process is asked to stop.
    tokio::select! {
        biased;
        res = &mut server_handle => return finish(&*plugin, &ctx, background, res).await,
        _ = signal::ctrl_c() => info!("SIGINT received, shutting down"),
        _ = terminate_signal() => info!("SIGTERM received, shutting down"),
    }

    shutdown.trigger();

    // Graceful shutdown drains in-flight requests — including server-streaming
    // ones (`stt_process`) that a busy plugin may hold open indefinitely. Give
    // them a bounded grace period, then stop waiting: a process asked to
    // terminate has to terminate.
    let res = match tokio::time::timeout(SHUTDOWN_GRACE, &mut server_handle).await {
        Ok(res) => res,
        Err(_) => {
            warn!(
                "gRPC server still draining after {}s — forcing shutdown",
                SHUTDOWN_GRACE.as_secs()
            );
            server_handle.abort();
            server_handle.await
        }
    };
    finish(&*plugin, &ctx, background, res).await
}

/// How long a shutdown waits for in-flight RPCs before forcing the issue.
///
/// Must not exceed the daemon's own grace (`spec/limits.yaml`), or the tidy
/// path never runs: the daemon kills the process group first.
const SHUTDOWN_GRACE: std::time::Duration =
    std::time::Duration::from_secs(crate::limits::PLUGIN_STOP_GRACE_SECS);

/// Stop the background loops, run `on_shutdown()`, and turn the server's exit
/// into this function's return value — a serve failure must surface as `Err`,
/// not as a silent exit 0.
async fn finish<P: PluginCapability>(
    plugin: &P,
    ctx: &PluginContext,
    background: Vec<JoinHandle<()>>,
    res: Result<Result<(), tonic::transport::Error>, tokio::task::JoinError>,
) -> Result<()> {
    for task in background {
        task.abort();
    }
    plugin.on_shutdown(ctx).await;

    match res {
        Ok(Ok(())) => {
            info!("Plugin shut down cleanly");
            Ok(())
        }
        Ok(Err(e)) => Err(anyhow::Error::new(e).context("Plugin gRPC server failed")),
        // Aborted after the grace period — a forced but intentional shutdown.
        Err(e) if e.is_cancelled() => {
            info!("Plugin shut down (server forcibly stopped)");
            Ok(())
        }
        Err(e) => Err(anyhow::Error::new(e).context("Plugin gRPC server task failed")),
    }
}

/// Resolves when the process receives `SIGTERM` — how the daemon (and every
/// service manager) asks a child to stop. Never resolves on non-Unix.
async fn terminate_signal() {
    #[cfg(unix)]
    {
        match signal::unix::signal(signal::unix::SignalKind::terminate()) {
            Ok(mut sig) => {
                sig.recv().await;
            }
            Err(e) => {
                warn!("Cannot listen for SIGTERM: {e}");
                std::future::pending::<()>().await;
            }
        }
    }
    #[cfg(not(unix))]
    {
        std::future::pending::<()>().await;
    }
}

/// Fire-once shutdown trigger, shared by the signal handlers and the daemon's
/// `Shutdown` RPC. The first caller closes the oneshot that
/// `serve_with_incoming_shutdown` waits on; later calls are no-ops.
#[derive(Clone)]
struct ShutdownTrigger(Arc<Mutex<Option<oneshot::Sender<()>>>>);

impl ShutdownTrigger {
    fn new(tx: oneshot::Sender<()>) -> Self {
        Self(Arc::new(Mutex::new(Some(tx))))
    }

    fn trigger(&self) {
        // A poisoned lock only means some other task panicked while taking the
        // sender; shutting down is still the right thing to do.
        let taken = self
            .0
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .take();
        if let Some(tx) = taken {
            let _ = tx.send(());
        }
    }
}

// ── gRPC service implementation that delegates to the PluginCapability trait ──

/// How many chunks a streaming hook may run ahead of the daemon. Small on
/// purpose: back-pressure onto a plugin that is generating faster than the
/// daemon consumes is correct, and a deep buffer only hides it.
const STREAM_CHANNEL_CAPACITY: usize = 16;

struct CapabilityServiceImpl<P: PluginCapability> {
    plugin: Arc<P>,
    ctx: PluginContext,
    shutdown: ShutdownTrigger,
}

/// Run one hook, turning a panic into a `Status` the daemon can log.
///
/// `INTERNAL`, never `UNIMPLEMENTED`: the daemon reads the latter as *this hook
/// is absent* and stops calling it for the life of the process, which would
/// turn one panic into a plugin that has quietly lost a capability.
async fn catch<F: std::future::Future>(
    hook: &str,
    fut: F,
) -> Result<F::Output, tonic::Status> {
    crate::panics::catch(hook, fut).await.map_err(Into::into)
}

/// Run one hook that already returns `Result<_, ToolError>`, turning a panic
/// into the same in-band error a returned `Err` would have been.
async fn caught_tool<T, F: std::future::Future<Output = Result<T, ToolError>>>(
    hook: &str,
    fut: F,
) -> Result<T, ToolError> {
    match crate::panics::catch(hook, fut).await {
        Ok(res) => res,
        Err(panicked) => Err(panicked.into()),
    }
}

/// An error that reached the daemon *after* the response stream opened. The
/// headers are already sent, so there is no status left to set — the protocol's
/// place for this is the stream's own error variant.
fn ai_error_chunk(error: ToolError) -> proto::PluginAiStreamChunk {
    proto::PluginAiStreamChunk {
        content: Some(proto::plugin_ai_stream_chunk::Content::Error(error.wire_string())),
        error_detail: Some(error.to_plugin_error()),
    }
}

