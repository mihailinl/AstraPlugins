    /// `Some(empty)` and `None` are different statements.
    ///
    /// The daemon always sets `ASTRA_PLUGIN_CAPABILITIES`, empty included:
    /// empty is "this manifest declares none", and the variable being ABSENT is
    /// "the daemon predates §5.4". Collapsing the two would let a plugin whose
    /// manifest declares nothing quietly register with whatever it was built
    /// with — overriding the file the user actually consented to.
    #[test]
    fn a_manifest_that_declares_nothing_is_not_the_same_as_an_old_daemon() {
        assert!(
            resolve_capabilities(vec![], Some(vec![String::new()]), &[String::from("tools")])
                .is_empty(),
            "an empty statement from the daemon is still the daemon's statement",
        );
        assert_eq!(
            resolve_capabilities(vec![], None, &[String::from("tools")]),
            argv(&["tools"]),
            "no statement at all is what falls back to the binary's declaration",
        );
    }

    #[test]
    fn an_older_daemon_that_states_nothing_falls_back_to_the_binarys_declaration() {
        assert_eq!(
            resolve_capabilities(vec![], None, &[String::from("tools")]),
            argv(&["tools"])
        );
        // Whitespace and empty entries from `ASTRA_PLUGIN_CAPABILITIES=tools,,`
        // are not capabilities.
        assert_eq!(
            resolve_capabilities(vec![], Some(argv(&["tools", " ", ""])), &[]),
            argv(&["tools"])
        );
        assert!(resolve_capabilities(vec![], None, &[]).is_empty());
    }

    /// The parse of the daemon's variable, including the two cases that are not
    /// a list: unset, and set to the empty string.
    #[test]
    fn the_capability_variable_parses_the_way_the_daemon_writes_it() {
        // `std::env::set_var` is process-global; this test owns the variable
        // and restores it, and no other test in this module reads it.
        let previous = std::env::var(CAPABILITIES_ENV).ok();

        unsafe { std::env::remove_var(CAPABILITIES_ENV) };
        assert_eq!(capabilities_from_env(), None, "unset is `None`, not empty");

        unsafe { std::env::set_var(CAPABILITIES_ENV, "") };
        assert_eq!(
            resolve_capabilities(vec![], capabilities_from_env(), &[String::from("tools")]),
            Vec::<String>::new(),
            "set-but-empty is the daemon saying this manifest declares none",
        );

        unsafe { std::env::set_var(CAPABILITIES_ENV, "tools,triggers") };
        assert_eq!(
            resolve_capabilities(vec![], capabilities_from_env(), &[]),
            argv(&["tools", "triggers"]),
        );

        match previous {
            Some(v) => unsafe { std::env::set_var(CAPABILITIES_ENV, v) },
            None => unsafe { std::env::remove_var(CAPABILITIES_ENV) },
        }
    }

