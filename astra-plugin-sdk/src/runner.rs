    async fn ai_complete(
        &self,
        request: tonic::Request<proto::PluginAiCompleteRequest>,
    ) -> Result<tonic::Response<Self::AiCompleteStream>, tonic::Status> {
        let req = request.into_inner();
        let (tx, mut rx) = tokio::sync::mpsc::channel::<AiChunk>(STREAM_CHANNEL_CAPACITY);
        let plugin = self.plugin.clone();
        let ctx = self.ctx.clone();
        let task = tokio::spawn(async move { plugin.ai_complete(&ctx, req, tx).await });

        // Same first-chunk rule as `tts_synthesize_stream`: a plugin that is not
        // an AI provider has to be able to say `UNIMPLEMENTED`, and a status can
        // only be set before the first chunk goes out.
        let Some(first) = rx.recv().await else {
            return match task.await {
                Ok(Ok(())) => {
                    let done: Self::AiCompleteStream =
                        Box::pin(tokio_stream::once(Ok(AiChunk::Done.into())));
                    Ok(tonic::Response::new(done))
                }
                Ok(Err(e)) => Err(hook_status(e)),
                Err(e) => Err(tonic::Status::internal(format!("ai_complete panicked: {e}"))),
            };
        };

        let out = async_stream::stream! {
            yield Ok::<proto::PluginAiStreamChunk, tonic::Status>(first.into());
            while let Some(chunk) = rx.recv().await {
                yield Ok(chunk.into());
            }
            // The turn is over. `Done` is appended by the SDK so no plugin has
            // to remember to send it, and an error that arrives mid-stream is
            // delivered as the stream's own error variant — the daemon's AI loop
            // reads that and stops; a `Status` here would be dropped.
            match task.await {
                Ok(Ok(())) => yield Ok(AiChunk::Done.into()),
                Ok(Err(e)) => yield Ok(ai_error_chunk(ToolError::from(e))),
                Err(e) => yield Ok(ai_error_chunk(ToolError::Internal(format!(
                    "ai_complete panicked: {e}"
                )))),
            }
        };
        Ok(tonic::Response::new(Box::pin(out)))
    }

