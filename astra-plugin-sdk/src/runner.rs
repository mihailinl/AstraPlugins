    /// The forward-compatibility contract: an unimplemented hook answers
    /// UNIMPLEMENTED, which the daemon reads as "absent" — not INTERNAL, which
    /// it reads as "broken". The streaming hooks are the interesting ones,
    /// because a status can only be set before the first chunk.
    #[tokio::test]
    async fn an_unimplemented_hook_answers_unimplemented_even_when_it_streams() {
        let addr = serve_guarded("", CapabilityAuth::Off).await;
        let mut c = connect(&addr).await;

        let err = c
            .tts_synthesize(proto::PluginTtsSynthesizeRequest::default())
            .await
            .unwrap_err();
        assert_eq!(err.code(), tonic::Code::Unimplemented, "{err}");

        let err = c
            .tts_synthesize_stream(proto::PluginTtsSynthesizeRequest::default())
            .await
            .unwrap_err();
        assert_eq!(err.code(), tonic::Code::Unimplemented, "{err}");

        let err = c
            .ai_complete(proto::PluginAiCompleteRequest::default())
            .await
            .unwrap_err();
        assert_eq!(err.code(), tonic::Code::Unimplemented, "{err}");

        for err in [
            c.stt_load(proto::SttLoadRequest::default()).await.unwrap_err(),
            c.stt_unload(proto::Empty {}).await.unwrap_err(),
            c.stt_get_load_state(proto::Empty {}).await.unwrap_err(),
            c.tts_activate(proto::PluginTtsActivateRequest::default())
                .await
                .unwrap_err(),
        ] {
            assert_eq!(err.code(), tonic::Code::Unimplemented, "{err}");
        }
    }

    /// 5.2, over a real socket: a per-call failure is DATA. It comes back as a
    /// successful RPC with `success = false` and a coded message, because the
    /// AI loop has to read it. A `Status` here would be a transport failure and
    /// the model would be told nothing.
    #[tokio::test]
    async fn a_tool_failure_is_in_band_and_carries_its_code() {
        struct NeedsAKey;
        #[async_trait::async_trait]
        impl PluginCapability for NeedsAKey {
            type Config = NoConfig;
            async fn call_tool(
                &self,
                _ctx: &PluginContext,
                _name: &str,
                _args: &str,
            ) -> Result<String, ToolError> {
                Err(ToolError::not_configured_with(
                    "api_key",
                    "OpenAI API key is not set",
                ))
            }
        }

        let addr = serve_plugin(NeedsAKey, "", CapabilityAuth::Off).await;
        let mut c = connect(&addr).await;
        let resp = c
            .call_tool(proto::PluginCallToolRequest {
                tool_name: "ask".into(),
                arguments_json: "{}".into(),
            })
            .await
            .expect("a failed tool call is still a successful RPC")
            .into_inner();
        assert!(!resp.success);
        assert!(resp.error.starts_with("NOT_CONFIGURED: "), "{}", resp.error);
        assert!(resp.error.contains("api_key"), "{}", resp.error);
    }

    /// 5.4: `OnActiveTriggers` has to reach the CONTEXT, not just the hook.
    /// Before this, `ActiveTriggers` was a type with no writer — every
    /// `contains()` answered false and plugins fired triggers nobody wanted.
    #[tokio::test]
    async fn active_triggers_reach_the_context_before_the_hook_runs() {
        use std::sync::atomic::{AtomicBool, Ordering};
        static SAW_IT: AtomicBool = AtomicBool::new(false);

        struct Watcher;
        #[async_trait::async_trait]
        impl PluginCapability for Watcher {
            type Config = NoConfig;
            async fn on_active_triggers(&self, ctx: &PluginContext, _types: Vec<String>) {
                // The hook cannot observe the older value.
                SAW_IT.store(ctx.active_triggers().contains("on_roll_value"), Ordering::SeqCst);
            }
        }

        let addr = serve_plugin(Watcher, "", CapabilityAuth::Off).await;
        connect(&addr)
            .await
            .on_active_triggers(proto::PluginActiveTriggersMsg {
                trigger_types: vec!["on_roll_value".into()],
            })
            .await
            .unwrap();
        assert!(SAW_IT.load(Ordering::SeqCst));
    }

    /// A Rust plugin can serve AI completions and stream TTS — 5.4's acceptance,
    /// end to end over a socket.
    #[tokio::test]
    async fn a_plugin_can_serve_ai_completions_and_stream_tts() {
        struct Provider;
        #[async_trait::async_trait]
        impl PluginCapability for Provider {
            type Config = NoConfig;

            async fn ai_complete(
                &self,
                _ctx: &PluginContext,
                req: AiRequest,
                chunks: tokio::sync::mpsc::Sender<AiChunk>,
            ) -> Result<()> {
                // The reasoning knobs were on the wire and reachable by no SDK
                // before 0.6; a provider that cannot see them cannot honour the
                // user's setting.
                if req.show_reasoning {
                    chunks.send(AiChunk::thinking("hmm")).await?;
                }
                chunks.send(AiChunk::text("hello")).await?;
                chunks.send(AiChunk::text(req.reasoning_effort)).await?;
                Ok(())
            }

            async fn tts_synthesize_stream(
                &self,
                _ctx: &PluginContext,
                req: TtsRequest,
                chunks: tokio::sync::mpsc::Sender<AudioChunk>,
            ) -> Result<()> {
                for (i, _word) in req.text.split_whitespace().enumerate() {
                    chunks.send(AudioChunk::new(vec![i as u8], 24_000)).await?;
                }
                chunks.send(AudioChunk::new(vec![], 24_000).last()).await?;
                Ok(())
            }
        }

        use tokio_stream::StreamExt;
        let addr = serve_plugin(Provider, "", CapabilityAuth::Off).await;
        let mut c = connect(&addr).await;

        let mut stream = c
            .ai_complete(proto::PluginAiCompleteRequest {
                reasoning_effort: "high".into(),
                show_reasoning: true,
                ..Default::default()
            })
            .await
            .unwrap()
            .into_inner();
        let mut got = Vec::new();
        while let Some(chunk) = stream.next().await {
            got.push(chunk.unwrap().content.unwrap());
        }
        use proto::plugin_ai_stream_chunk::Content;
        assert!(matches!(&got[0], Content::ThinkingDelta(t) if t == "hmm"));
        assert!(matches!(&got[1], Content::TextDelta(t) if t == "hello"));
        assert!(matches!(&got[2], Content::TextDelta(t) if t == "high"));
        // `Done` is appended by the SDK, so no plugin has to remember it.
        assert!(matches!(got[3], Content::Done(true)));

        let mut stream = c
            .tts_synthesize_stream(proto::PluginTtsSynthesizeRequest {
                text: "one two three".into(),
                ..Default::default()
            })
            .await
            .unwrap()
            .into_inner();
        let mut chunks = Vec::new();
        while let Some(chunk) = stream.next().await {
            chunks.push(chunk.unwrap());
        }
        assert_eq!(chunks.len(), 4);
        assert!(chunks.last().unwrap().is_last);
    }

